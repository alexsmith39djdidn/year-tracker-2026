function zoneOf(v) {
  if (v === null || v === undefined) return null;
  for (var i = 0; i < ZONES.length; i++) {
    if (v >= ZONES[i].lo && v <= ZONES[i].hi) return ZONES[i];
  }
  return ZONES[ZONES.length - 1];
}

function colorOf(v) {
  var z = zoneOf(v);
  return z ? 'var(' + z.v + ')' : 'var(--fade)';
}

/* ─── Открытые шкалы: балл выше 100 ──────────────────────────
   До нормы — линейно. Сверх нормы каждые +10% дают +5 балла:
   105% → 103, 120% → 110, 150% → 125, 200% → 150 (потолок).
   Сжатие сверху нарочно: перевыполнение вдвое не значит «вдвое лучше»,
   и не даёт одной шкале утащить весь индекс. */
var OPEN_MAX = 150;
function openScore(fact, norm) {
  if (!norm) return null;
  var pct = fact / norm * 100;
  if (pct <= 100) return Math.round(pct);
  return Math.min(OPEN_MAX, Math.round(100 + (pct - 100) * 0.5));
}

/* ─── Протухание замеров — по физиологии ─────────────────────
   Растренированность идёт с разной скоростью:
   · выносливость (аэробная) — держится ~3 недели без нагрузки, потом
     заметно падает (VO2max −4…−14% за месяц простоя)
   · сила — держится ~6 недель, дальше медленно уходит
   · осанка, гибкость — меняются медленно, но и мерить их надо заново
   grace — дней без потерь; perWeek — сколько баллов уходит за неделю после;
   floor — ниже половины замера не опускаем: ноль не наступает от старости.
   STALE_DAYS — после этого замер не считается совсем, нужен новый.
   maintained: true снимает протухание — деятельность идёт, форма держится. */
var DECAY = {
  endurance: { grace: 21, perWeek: 4 },
  strength:  { grace: 42, perWeek: 3 },
  posture:   { grace: 45, perWeek: 2 },
  flex:      { grace: 45, perWeek: 2 }
};
var STALE_DAYS = 120;

function parseDMY(s) { var p = s.split('.'); return new Date(+p[2], +p[1] - 1, +p[0]); }
function parseYMD(s) { var p = s.split('-'); return new Date(+p[0], +p[1] - 1, +p[2]); }
function ageDays(s) {
  if (!s.measured) return null;
  return Math.round((parseDMY(RATING.date) - parseYMD(s.measured)) / 86400000);
}

// Эффективный балл шкалы: что реально идёт в счёт (null = не идёт).
function effective(s) {
  if (s.raw) return null;
  if (s.score === null || s.score === undefined) return null;
  if (s.stale) return null;
  if (!s.kind) return s.score;
  var age = ageDays(s);
  if (age === null) return s.score;
  if (age > STALE_DAYS) return null;
  if (s.maintained) return s.score;
  var d = DECAY[s.kind];
  if (!d || age <= d.grace) return s.score;
  var lost = d.perWeek * (age - d.grace) / 7;
  return Math.max(Math.round(s.score - lost), Math.round(s.score * 0.5));
}

// Почему балл не равен замеру — короткая пометка для карточки
function decayNote(s) {
  if (s.raw || s.score === null || s.score === undefined) return '';
  if (s.stale) return '⚠ устарел';
  if (!s.kind) return '';
  var age = ageDays(s);
  if (age === null) return '';
  if (age > STALE_DAYS) return '⚠ замеру ' + age + ' дн — нужен новый';
  if (s.maintained) return 'замеру ' + age + ' дн · держится';
  var e = effective(s);
  if (e !== s.score) return 'замеру ' + age + ' дн · −' + (s.score - e) + ' за простой';
  return 'замеру ' + age + ' дн';
}

